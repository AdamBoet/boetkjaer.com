-- Habits for the lab's Habit Helper page. Each habit reminds via Web Push
-- every interval_minutes, skipping its quiet hours (Europe/Copenhagen wall
-- time; both null = no quiet hours). Only reachable through /api/habits
-- (behind the lab login) and /api/habit-tick (shared secret): RLS on, no
-- policies, service_role bypasses it.

create table if not exists habits (
  id bigint generated by default as identity primary key,
  name text not null check (length(name) between 1 and 100),
  interval_minutes int not null check (interval_minutes between 5 and 43200),
  quiet_start time,
  quiet_end time,
  active boolean not null default true,
  next_due_at timestamptz not null,
  created_at timestamptz not null default now(),
  check ((quiet_start is null) = (quiet_end is null))
);

create index if not exists habits_due_idx on habits (next_due_at) where active;

alter table habits enable row level security;

revoke all on habits from anon, authenticated;
grant select, insert, update, delete on habits to service_role;

