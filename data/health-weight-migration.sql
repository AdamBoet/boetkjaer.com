-- Body weight log for the lab's Health page. Only reachable through
-- /api/health, which sits behind the lab login: RLS on, no policies,
-- service_role bypasses it.

create table if not exists health_weight_entries (
  id bigint generated by default as identity primary key,
  weight_kg numeric(5,1) not null check (weight_kg > 0 and weight_kg < 500),
  created_at timestamptz not null default now()
);

create index if not exists health_weight_entries_created_at_idx
  on health_weight_entries (created_at desc);

alter table health_weight_entries enable row level security;

revoke all on health_weight_entries from anon, authenticated;
grant select, insert, update, delete on health_weight_entries to service_role;
