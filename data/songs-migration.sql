-- Saved songs for the hanzi lab's Songs tab. Lyrics come from LRCLIB and are
-- stored converted to Simplified. `synced_lyrics` keeps the line timestamps
-- so playback can be added later without fetching every song again.
--
-- Unlike the card tables, there is deliberately no anon/authenticated read
-- policy: lyrics are copyrighted, so they're only reachable through
-- /api/songs, which sits behind the lab login. RLS is on with no policies,
-- and service_role bypasses it.

create table if not exists songs (
  id bigint generated by default as identity primary key,
  lrclib_id bigint not null unique,
  title text not null,
  artist text not null,
  album text,
  duration_seconds integer,
  lyrics text not null,
  synced_lyrics text,
  created_at timestamptz not null default now()
);

alter table songs enable row level security;

revoke all on songs from anon, authenticated;
grant select, insert, update, delete on songs to service_role;
