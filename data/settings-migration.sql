-- Personal info shown in the lab's Settings window. Free-form label/value
-- rows; `secret` rows (CPR) are masked in the UI until revealed. Only
-- reachable through /api/settings (behind the lab login): RLS on, no
-- policies, service_role bypasses it. Values are stored unencrypted.

create table if not exists personal_info (
  id bigint generated by default as identity primary key,
  label text not null check (length(label) between 1 and 60),
  value text not null default '' check (length(value) <= 500),
  secret boolean not null default false,
  position int not null default 0,
  created_at timestamptz not null default now()
);

alter table personal_info enable row level security;
revoke all on personal_info from anon, authenticated;
grant select, insert, update, delete on personal_info to service_role;

insert into personal_info (label, secret, position) values
  ('Name', false, 1), ('Birthday', false, 2), ('Address', false, 3),
  ('CPR', true, 4), ('Phone', false, 5), ('Email', false, 6);

-- On/off switches for notifications that aren't habits or daily reminders:
-- 'mandarin_nightly' is read by mandarin-pipeline/daily_refresh.py,
-- 'mandarin_watchdog' by /api/pipeline-watchdog. Edited in Settings.
create table if not exists notification_toggles (
  id text primary key,
  label text not null,
  enabled boolean not null default true,
  position int not null default 0,
  updated_at timestamptz not null default now()
);

alter table notification_toggles enable row level security;
revoke all on notification_toggles from anon, authenticated;
grant select, insert, update, delete on notification_toggles to service_role;

insert into notification_toggles (id, label, position) values
  ('mandarin_nightly', 'Nightly run summary', 1),
  ('mandarin_watchdog', 'Missed or stuck runs', 2)
on conflict (id) do nothing;
